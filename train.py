#!/usr/bin/env python3
"""Train the boot-sector net and export it.

Model (all integers, runs in 16-bit real mode):
    pre[k]    = E1[c1][k] + E2[c2][k]          c1 = previous char, c2 = the one before
    h[k]      = max(0, pre[k])                 ReLU hidden layer, K units
    logit[j]  = sum_k h[k] * W[j][k]           28 output symbols
    next char = argmax_j (logit[j] + noise)    noise makes it a sampler

Weights are 4-bit, stored offset-binary (w + 8 in 0..15) so the asm needs no sign
handling: pre = n1 + n2 - 16, and the constant 8*sum(h) that offset-binary adds to
every logit cancels in the argmax.

usage: train.py [K=6] [steps=6000] [seeds=6]
"""
import sys
import time

import numpy as np

from explore import ALPHA, V, count_tensor, load

LO, HI = -8, 7


def fit(n2, k, steps, seed, lr0=0.12, lr1=0.002):
    rng = np.random.default_rng(seed)
    q = lambda x: np.clip(np.round(x), LO, HI)
    N, T = n2, n2.sum()
    nctx = N.sum(-1, keepdims=True)
    P = {n: rng.normal(0, 2.0, (V, k)) for n in ("E1", "E2", "W")}
    P["a"] = np.array(0.15)
    m = {n: np.zeros_like(v) for n, v in P.items()}
    s = {n: np.zeros_like(v) for n, v in P.items()}
    best = (1e9, None)
    for t in range(1, steps + 1):
        lr = lr1 + 0.5 * (lr0 - lr1) * (1 + np.cos(np.pi * t / steps))
        E1, E2, W = q(P["E1"]), q(P["E2"]), q(P["W"])
        pre = E2[:, None, :] + E1[None, :, :]
        h = np.maximum(pre, 0)
        z = h @ W.T
        lg = P["a"] * z
        lg = lg - lg.max(-1, keepdims=True)
        p = np.exp(lg)
        p /= p.sum(-1, keepdims=True)
        loss = -(N * np.log(p + 1e-12)).sum() / T / np.log(2)
        if loss < best[0]:
            best = (loss, {n: v.copy() for n, v in P.items()})
        dlog = (p * nctx - N) / T
        G = {"a": np.array((dlog * z).sum())}
        dz = dlog * P["a"]
        G["W"] = np.einsum("abj,abk->jk", dz, h)
        dpre = (dz @ W) * (pre > 0)
        G["E1"], G["E2"] = dpre.sum(0), dpre.sum(1)
        for n in P:
            m[n] = 0.9 * m[n] + 0.1 * G[n]
            s[n] = 0.999 * s[n] + 0.001 * G[n] ** 2
            step = lr * (m[n] / (1 - 0.9**t)) / (np.sqrt(s[n] / (1 - 0.999**t)) + 1e-8)
            P[n] = P[n] - (step * 0.02 if n == "a" else step)
            if n != "a":
                P[n] = np.clip(P[n], LO - 0.49, HI + 0.49)
    loss, P = best
    return loss, {n: (q(P[n]).astype(np.int64) if n != "a" else float(P[n])) for n in P}


def bits_per_char(n2, M, alpha):
    pre = M["E2"][:, None, :] + M["E1"][None, :, :]
    z = np.maximum(pre, 0) @ M["W"].T
    lg = alpha * z
    lg = lg - lg.max(-1, keepdims=True)
    p = np.exp(lg)
    p /= p.sum(-1, keepdims=True)
    return -(n2 * np.log2(p + 1e-12)).sum() / n2.sum()


def pack(M):
    """Rows of K/2 bytes: low nibble = unit 2m, high nibble = unit 2m+1, value+8."""
    out = {}
    for name in ("E1", "E2", "W"):
        a = M[name] + 8
        assert a.min() >= 0 and a.max() <= 15
        out[name] = (a[:, 0::2] | (a[:, 1::2] << 4)).astype(np.uint8)
    return out


def write_inc(M, path):
    packed = pack(M)
    lines = [
        "; generated by train.py - do not edit",
        "; E1/E2: one row per symbol (0=space, 1..26=a..z), 3 bytes each.",
        "; W: rows stored in REVERSE symbol order (z first) so the asm can count down.",
        "",
    ]
    for name in ("E1", "E2", "W"):
        lines.append(f"{name}:")
        order = range(V - 1, -1, -1) if name == "W" else range(V)
        for i in order:
            ch = "space" if i == 0 else ALPHA[i]
            row = packed[name][i]
            lines.append("    db " + ", ".join(f"0x{b:02X}" for b in row) + f"    ; {ch}")
    open(path, "w").write("\n".join(lines) + "\n")


def main():
    k = int(sys.argv[1]) if len(sys.argv) > 1 else 6
    steps = int(sys.argv[2]) if len(sys.argv) > 2 else 6000
    seeds = int(sys.argv[3]) if len(sys.argv) > 3 else 6
    n2 = count_tensor(load())
    best = None
    for seed in range(seeds):
        t0 = time.time()
        loss, M = fit(n2, k, steps, seed)
        print(f"seed {seed}: {loss:.4f} bits/char ({time.time() - t0:.0f}s)", flush=True)
        if best is None or loss < best[0]:
            best = (loss, M)
    loss, M = best
    # re-fit the temperature for the final integer weights
    alphas = np.linspace(0.02, 0.6, 291)
    alpha = float(alphas[np.argmin([bits_per_char(n2, M, a) for a in alphas])])
    loss = bits_per_char(n2, M, alpha)
    print(f"\nbest: {loss:.4f} bits/char, alpha={alpha:.3f} (noise scale ~ {1 / alpha:.1f} logit units)")
    print(f"weights: 3 x {V} rows x {k // 2} bytes = {3 * V * k // 2} bytes")
    np.savez("model.npz", E1=M["E1"], E2=M["E2"], W=M["W"], alpha=alpha, loss=loss)
    write_inc(M, "weights.inc")
    print("wrote model.npz, weights.inc")


if __name__ == "__main__":
    main()
